import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { renderAgentContext } from './agent-context.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
await rm(`${root}/dist`, { recursive: true, force: true });
await mkdir(`${root}/dist`, { recursive: true });
await cp(`${root}/src`, `${root}/dist`, { recursive: true });
const pricing = JSON.parse(await readFile(`${root}/docs/pricing-snapshot.json`, 'utf8'));
const markdown = renderAgentContext(pricing.verifiedDateNZ);
const agentPage = `${root}/dist/agent/index.html`;
const template = await readFile(agentPage, 'utf8');
const slot = '<!-- agent-context -->';
if (template.split(slot).length !== 2) throw new Error('Agent page must have exactly one Markdown slot');
const escapedMarkdown = markdown.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
await writeFile(agentPage, template.replace(slot, () => escapedMarkdown));
await writeFile(`${root}/dist/agent/lakeboard.md`, markdown);
await writeFile(`${root}/dist/.nojekyll`, '');
console.log('Built dist/ with self-contained static assets.');
